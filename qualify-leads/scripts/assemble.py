def cap_sources(text, limit=300):
    """Keep whole URLs, as many as fit in `limit` characters."""
    out = ""
    for part in [p.strip() for p in (text or "").split(";") if p.strip()]:
        cand = f"{out}; {part}" if out else part
        if len(cand) > limit:
            break
        out = cand
    return out


def enrich_skipped(run_dir):
    """Tier 1 companies the runner chose not to enrich (budget, JK's call), with the reason."""
    return {C.clean(r.get("company_key_final")): C.clean(r.get("reason"))
            for r in C.read_csv(C.work(run_dir, "06-enrich-skipped.csv")) if C.clean(r.get("company_key_final"))}


def paths(run_dir, run):
    d = run.get("as_of", "")
    label = run.get("source_label", "Leads")
    return (os.path.join(run_dir, f"{d} {label} Leads.csv"),
            os.path.join(run_dir, f"{d} hubspot-import.csv"))


def company_context(run_dir):
    """Company domains and owners per company_key_final, from the same facts label.py uses."""
    facts = L.load_facts(run_dir)
    L.apply_overrides(facts)
    ctx = {}
    for k in set(facts["companies"]) | set(facts["triage"]):
        c, _, _ = L.company_facts_for(k, facts)
        fk = C.clean(c.get("company_key_final")) or k
        doms = C.domain_list(c.get("domains", ""))
        if fk and not fk.startswith("name:"):
            doms.add(C.registrable_domain(fk))
        e = ctx.setdefault(fk, {"domains": set(), "name": ""})
        e["domains"] |= doms
        e["name"] = e["name"] or c.get("company_name_verified", "")
    for fk, cc in facts["crm_companies"].items():
        e = ctx.setdefault(fk, {"domains": set(), "name": ""})
        # a name-only HubSpot match is not trusted for ownership (label.py refuses it too)
        trusted = C.clean(cc.get("match_type")) != "name"
        e["owner"] = C.clean(cc.get("owner_name")) if trusted and C.yes(cc.get("owner_active")) else ""
    return ctx, facts


BOUNCEBAN_FIELDS = ["email", "bounceban_result", "score", "bulk_id"]


def committee_status(run_dir, as_of, ctx, facts, rows=None):
    """Email status for every committee member, from ONE source: the visitor's row in
    05-qualified.csv when the member is the visitor, else the member's facts with the
    HubSpot record and the run's single BounceBan bulk result applied."""
    crm = {}
    for r in C.read_csv(C.work(run_dir, "07-crm-committee.csv")):
        crm[(C.clean(r.get("company_key_final")), C.clean(r.get("email")).lower())] = r
    bounce = {C.clean(r["email"]).lower(): C.clean(r["bounceban_result"]).lower()
              for r in C.read_csv(C.work(run_dir, "07-bounceban.csv"))}
    visitor = {r["lead_id"]: r for r in (rows if rows is not None else C.read_csv(C.work(run_dir, "05-qualified.csv")))}
    out = []
    for fk in sorted(facts["committees"]):
        doms = ctx.get(fk, {}).get("domains", set())
        for m in facts["committees"][fk]:
            m = {k: C.clean(m.get(k, "")) for k in L.COMMITTEE_FIELDS}
            email = m["email"].lower()
            if email in bounce:
                m["bounceban_result"] = bounce[email]
            cr = crm.get((fk, email))
            in_hs = "not_checked" if not cr or not C.yes(cr.get("checked")) else \
                ("yes" if C.clean(cr.get("hs_contact_id")) else "no")
            v = dict(m, _as_of=as_of)
            if m["lead_id"] and m["lead_id"] in visitor and visitor[m["lead_id"]].get("email"):
                email = visitor[m["lead_id"]]["email"].lower()
                status = visitor[m["lead_id"]]["email_status"]  # same string as the CSV
            else:
                status = L.email_status(email, doms, "research", m["email_source"] == "hubspot" or in_hs == "yes", v)
            emp_dom = C.registrable_domain(m["employer_domain"])
            out.append(dict(m, email=email, email_status=status,
                            qualifies="yes" if status in C.QUALIFYING_EMAIL else "no",
                            domain_ok="yes" if (not email or C.email_domain(email) in doms) else "no",
                            employer_domain_ok="yes" if (not emp_dom or emp_dom in doms) else "no",
                            in_hubspot=in_hs))
    return out


def build_import(rows, members, tier1_keys, ctx, facts):
    out, skipped = [], []
    seen = set()

    def owner_for(fk):
        return ctx.get(fk, {}).get("owner") or L.DEFAULT_OWNER

    for r in rows:
        if r["action"] != "Contact now" or r["email_status"] not in C.QUALIFYING_EMAIL:
            continue
        ct = facts["crm_contacts"].get(r["lead_id"]) or {}
        if C.clean(ct.get("hs_contact_id")) or r["email_status"] == "From HubSpot":
            seen.add(r["email"])
            skipped.append({"name": r["name"], "company": r["company"], "why": "already a HubSpot contact"})
            continue
        if not C.yes(ct.get("checked")):
            seen.add(r["email"])
            skipped.append({"name": r["name"], "company": r["company"], "why": "not checked against HubSpot"})
            continue
        first, last = C.split_name(r["name"])
        seen.add(r["email"])
        out.append({"First Name": first, "Last Name": last, "Email": r["email"], "Job Title": r["title"],
                    "Company Name": r["company"], "Associate to company domain": r["company_key_final"],
                    "Contact owner": owner_for(r["company_key_final"]), "Priority": "First call",
                    "LinkedIn URL": r["linkedin"], "Lead Generated By": "Marketing",
                    "Lead Status": "New Marketing Lead"})
    for m in members:
        fk = m["company_key_final"]
        if fk not in tier1_keys or m["qualifies"] != "yes" or m["domain_ok"] != "yes" or \
                m["employer_domain_ok"] != "yes" or m["email"] in seen:
            continue
        if m["in_hubspot"] != "no":
            skipped.append({"name": m["full_name"], "company": ctx.get(fk, {}).get("name") or fk,
                            "why": "already a HubSpot contact" if m["in_hubspot"] == "yes" else "not checked against HubSpot"})
            continue
        prio = m["priority"] if m["priority"] in PRIORITIES else "Second wave"
        if m["email_status"] == "Verified, catch-all domain":
            prio += " (catch-all, deliverable per BounceBan)"
        first = m["first_name"] or C.split_name(m["full_name"])[0]
        last = m["last_name"] or C.split_name(m["full_name"])[1]
        seen.add(m["email"])
        out.append({"First Name": first, "Last Name": last, "Email": m["email"], "Job Title": m["title"],
                    "Company Name": ctx.get(fk, {}).get("name") or fk, "Associate to company domain": fk,
                    "Contact owner": owner_for(fk), "Priority": prio, "LinkedIn URL": m["linkedin_url"],
                    "Lead Generated By": "Marketing", "Lead Status": "New Marketing Lead"})
    for r in out:
        for k in ("First Name", "Last Name", "Job Title", "Company Name"):
            r[k] = C.desdash(r[k])
    return out, skipped


def summary(run, rows, roll, tier1, skipped, run_dir):
    matrix = defaultdict(lambda: defaultdict(int))
    for r in rows:
        matrix[r["action"]][r["verdict"]] += 1
    t1 = {t["company_key_final"]: t["tier1_reason"] for t in tier1}
    packets_dir = os.path.join(run_dir, "Packets")
    packets = set(os.listdir(packets_dir)) if os.path.isdir(packets_dir) else set()
    pick = lambda a: [r for r in rows if r["action"] == a]  # noqa: E731
    follow = []
    for c in roll:
        if c["best_action"] == "Drop":
            continue
        st = c["crm_state"]
        if st == "owned_inactive":
            follow.append(f"{c['company_name']}: HubSpot owner is inactive; reassign before outreach")
        elif st == "unowned":
            follow.append(f"{c['company_name']}: HubSpot company record is unowned; claim it")
        elif st == "possible_match":
            follow.append(f"{c['company_name']}: HubSpot match is by name only; confirm the record")
        elif st == "not_checked":
            follow.append(f"{c['company_name']}: not checked in HubSpot")
    for s in skipped:
        follow.append(f"{s['name']} at {s['company']}: left out of the import ({s['why']})")
    upgraded = []
    cand = C.read_csv(C.work(run_dir, "06-tier1-candidates.csv"))
    for c in cand:
        if c["company_key_final"] not in t1 and c["best_action"] == "Contact now":
            upgraded.append(c["company_name"])
    ledger = C.read_json(C.work(run_dir, "ledger-summary.json"), {})
    prof = run.get("profile", {})
    return {
        "source_label": run.get("source_label"), "as_of": run.get("as_of"),
        "date_first": prof.get("date_first"), "date_last": prof.get("date_last"),
        "zero_days": prof.get("zero_days", []),
        "source_rows_in_window": run.get("source_rows_in_window"), "merged_rows": run.get("merged_rows"),
        "final_rows": len(rows),
        "verdict_by_action": {a: {v: matrix[a][v] for v in C.VERDICTS} for a in C.ACTIONS},
        "contact_now": [{"name": r["name"], "company": r["company"], "next_step": r["next_step"]} for r in pick("Contact now")],
        "tell_account_owner": [{"name": r["name"], "company": r["company"], "next_step": r["next_step"]} for r in pick("Tell account owner")],
        "account_plays": [{"company": c["company_name"], "strength": c["account_strength"],
                           "tier1": t1.get(c["company_key_final"], ""),
                           "packet": C.packet_name(c["company_name"]) if C.packet_name(c["company_name"]) in packets else "",
                           "next_step": next(r["next_step"] for r in rows if r["lead_id"] == c["lead_row_id"])}
                          for c in roll if c["best_action"] == "Account play"],
        "review": [{"name": r["name"], "company": r["company"], "open_item": r["why"]} for r in pick("Review")],
        "tier1": [{"company": t["company_name"], "reason": t["tier1_reason"],
                   "enrichment_skipped": enrich_skipped(run_dir).get(t["company_key_final"], "")} for t in tier1],
        "crm_followups": follow, "upgraded_after_freeze": upgraded,
        "import_skipped": skipped, "ledger": ledger,
        "rows_with_label_warnings": sum(bool(r["label_warnings"]) for r in rows),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True)
    args = ap.parse_args(argv)
    run = C.load_run(args.run)
    as_of = C.parse_date(run.get("as_of"))
    rows = C.read_csv(C.work(args.run, "05-qualified.csv"))
    roll = C.read_csv(C.work(args.run, "05-company-rollup.csv"))
    tier1 = C.read_csv(C.work(args.run, "06-tier1.csv"))
    canon = C.read_csv(C.work(args.run, "01-canonical.csv"))
    if {r["lead_id"] for r in rows} != {r["lead_id"] for r in canon}:
        sys.exit("05-qualified.csv does not cover every canonical row; rerun label.py")
    rows.sort(key=lambda r: int(r["rank"]))

    final_path, import_path = paths(args.run, run)
    raw_cols = {"Name", "Title", "Company", "City", "State"}
    final = [{h: (C.desdash(r.get(k, "")) if h in raw_cols else r.get(k, "")) for h, k in FINAL_COLUMNS}
             for r in rows]
    for f in final:
        f["Sources"] = cap_sources(f["Sources"])
    C.write_csv(final_path, final, [h for h, _ in FINAL_COLUMNS], bom=True)

    ctx, facts = company_context(args.run)
    members = committee_status(args.run, as_of, ctx, facts, rows)
    C.write_csv(C.work(args.run, "08-committee-status.csv"), members, COMMITTEE_STATUS_FIELDS)
    tier_keys = {t["company_key_final"] for t in tier1}
    imp, skipped = build_import(rows, members, tier_keys, ctx, facts)
    C.write_csv(import_path, imp, IMPORT_COLUMNS, bom=True)

    summ = summary(run, rows, roll, tier1, skipped, args.run)
    C.write_json(C.work(args.run, "08-summary.json"), summ)
    C.append_log(args.run, f"S8 final_rows={len(final)} import_rows={len(imp)} import_skipped={len(skipped)} "
                           f"committee_members={len(members)}")
    print(f"wrote {final_path} ({len(final)} rows)")
    print(f"wrote {import_path} ({len(imp)} rows; {len(skipped)} left out, see 08-summary.json)")


if __name__ == "__main__":
    main()
